  function charts() {
    var top10 = DATA.rows.slice(0, 10);
    var byCat = {};
    DATA.rows.forEach(function (r) {
      var c = r.category || 'Other';
      byCat[c] = (byCat[c] || 0) + r.implied_value_usd;
    });
    var cats = Object.keys(byCat).map(function (c) { return { category: c, value: byCat[c] }; })
      .sort(function (a, b) { return b.value - a.value; }).slice(0, 8);
    return el('div', { class: 'charts' },
      barChart('Top 10 by implied value', 'The strongest launch candidates on this snapshot.', top10, function (r) { return r.implied_value_usd; }, function (r) { return r.rank + '. ' + r.name; }),
      barChart('Implied value by category', 'Total implied value of the ranked rows in each category.', cats, function (c) { return c.value; }, function (c) { return c.category; })
    );
  }

