// The token radar's model, radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board ranks every genuine launch candidate the snapshot holds: a protocol that records no
// token and is not a wrapped, staked or bridged product of a token that already trades, not a
// centralised exchange and not a versioned pool. That is the watchlist's own exclusion rule, applied
// to the whole universe instead of only the floor, so the board is 178 rows of protocols that could
// plausibly issue a token one day. The protocols it leaves out are not hidden: the dashboard shows
// them in a Set aside view with the reason each one is set aside, and the live-token protocols in a
// Live token view with their market caps.
//
// Implied value follows only from the snapshot's own figures, and the multiple is the model's one
// real change from the starter's flat 0.25: for each category, the multiple is the median market
// cap per dollar of TVL of the protocols in that category whose token already trades, computed
// from this snapshot at run time, never from a hand-kept table. A category with fewer than three
// live protocols falls back to the whole market's median. The multiple is clamped so one outlier
// category cannot dominate the board.
//
//   multiple     = median(mcap_usd / tvl_usd) over live protocols of the category (n >= 3),
//                  else the global median; clamped to [0.02, 2.5]
//   growth       = clamp(change_7d, -60, 120) per cent
//   growthMult   = 1 + (growth / 100) x 0.5
//   maturity     = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   implied      = max(1, round(tvl_usd x multiple x growthMult x maturity))
//
// No protocol name is ever special-cased: the same function scores every row, and the multiples
// are recomputed from whatever snapshot the program reads, so a future snapshot re-ranks itself.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
